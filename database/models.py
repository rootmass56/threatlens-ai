    parser_version: Mapped[str] = mapped_column(String(32), nullable=False, default="0.3.0")
    engine_version: Mapped[str] = mapped_column(String(32), nullable=False, default="0.3.0")
    total_events: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    total_alerts: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    total_incidents: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
